//! Dump emitters call each language's public accessors. Only traversal and
//! serialization are shared; parsing and parsed values remain independent.
use super::*;
mod complex;

pub(super) fn generate(items: &Items, silk: bool) -> syn::Result<String> {
    let module = items
        .parse_module_path
        .segments
        .last()
        .unwrap()
        .ident
        .to_string();
    let parse_path = items
        .parse_module_path
        .segments
        .iter()
        .map(|segment| segment.ident.to_string())
        .collect::<Vec<_>>()
        .join("::");
    let silk_path = parse_path.replace("::", ".");
    let rust_path = parse_path
        .strip_prefix("read_fonts::")
        .unwrap_or(&parse_path);
    let mut out = "// THIS FILE IS AUTOGENERATED. DO NOT EDIT.\n// Copyright 2022 the Fontations Authors. Licensed under Apache-2.0 or MIT.\n".to_owned();
    if silk {
        if module == "layout" {
            out.push_str("import extensions_sets\n");
        }
        if module == "cmap" {
            out.push_str("import extensions_cmap\n");
        }
        if module == "name" {
            out.push_str("import extensions_name\n");
        }
        if module == "post" {
            out.push_str("import extensions_post\n");
        }
        if module == "hmtx" || module == "vmtx" {
            out.push_str("import extensions_metrics\n");
        }
        if module == "post" {
            out.push_str("import read_fonts.tables.post { PString }\n");
        }
        let names = items
            .iter()
            .filter(|i| !matches!(i, Item::Table(t) if t.attrs.write_only.is_some()))
            .filter(|i| {
                (module != "gvar" && module != "cvar")
                    || !matches!(
                        i.name().to_string().as_str(),
                        "TupleVariationCount" | "TupleVariationHeader"
                    )
            })
            .map(|i| i.name().to_string())
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(out,"import {silk_path} {{ {names} }}\nimport read_fonts.lib {{ FontData, FontRead, ReadError, ScalarArray, ComputedArray, VarLenArray, VarLenIter, ReadArgs2, ReadArgs3, ArrayOfOffsets, ArrayOfNullableOffsets }}\nimport font_types.lib {{ Fixed, F2Dot14, FWord, UfWord, Tag, MajorMinor, Version16Dot16, LongDateTime, Uint24, Int24, GlyphId16, GlyphId24, GlyphId, NameId, Nullable, Offset16, Offset24, Offset32 }}\nimport dump_support {{ DumpPath, DumpTable, scalar, absent, readError, versionBits, bytes }}\nimport silk.core.option {{ Option }}\nimport silk.core.result {{ Result }}\nimport silk.io.writer {{ Writer, WriterError }}\nimport silk.num.u8\nimport silk.num.u16\nimport silk.num.u32\nimport silk.num.u64\n").unwrap();
    } else {
        writeln!(out,"#![allow(unused_imports, unused_variables, dead_code, non_snake_case)]\nuse read_fonts::{{{rust_path}::*, types::*, FontData, ReadError, FontRead}};\nuse std::io::{{self, Write}};\n").unwrap();
    }
    complex::imports(&mut out, &module, silk);
    let dc = DumpContext {
        cx: Context { items },
        silk,
    };
    for item in items.iter() {
        match item {
            Item::Table(t) if t.attrs.write_only.is_none() => {
                dc.fields(&mut out, &t.name.to_string(), &t.fields, false)?
            }
            Item::Record(r) => dc.fields(&mut out, &r.name.to_string(), &r.fields, true)?,
            Item::Format(f) => dc.format(&mut out, f)?,
            Item::GenericGroup(g) => dc.group(&mut out, g)?,
            _ => (),
        }
    }
    if module == "layout" {
        dc.trait_impl(&mut out, "FeatureParams");
    }
    if module == "meta" {
        dc.trait_impl(&mut out, "Metadata");
    }
    if module == "bitmap" {
        dc.trait_impl(&mut out, "IndexSubtable");
    }
    dc.top_levels(&mut out, items)?;
    Ok(out)
}
struct DumpContext<'a> {
    cx: Context<'a>,
    silk: bool,
}
impl DumpContext<'_> {
    fn top_levels(&self, out: &mut String, items: &Items) -> syn::Result<()> {
        if self.silk {
            writeln!(out, "import read_fonts.lib {{ FontRef }}\npub effect fn dumpTables<'a>(path: &mut DumpPath, font: &FontRef<'a>) -> () ! WriterError ? &mut Writer {{").unwrap();
        } else {
            writeln!(out, "pub fn dump_tables(out: &mut impl Write, path: &str, font: &read_fonts::FontRef<'_>) -> io::Result<()> {{\n use read_fonts::FontRead;").unwrap();
        }
        for item in items.iter() {
            let Item::Table(table) = item else {
                continue;
            };
            let Some(tag) = &table.attrs.tag else {
                continue;
            };
            let name = &table.name;
            let tag = tag.value();
            let tag_value = u32::from_be_bytes(tag.as_bytes().try_into().unwrap());
            if table.attrs.read_args.is_some() {
                let (method, rust_method) = match name.to_string().as_str() {
                    "Hmtx" => ("hmtx", "hmtx"),
                    "HmtxExtended" => ("hmtxExtended", "hmtx_extended"),
                    "Vmtx" => ("vmtx", "vmtx"),
                    "VmtxExtended" => ("vmtxExtended", "vmtx_extended"),
                    "Hdmx" => ("hdmx", "hdmx"),
                    "Sbix" => ("sbix", "sbix"),
                    _ => {
                        return Err(syn::Error::new(
                            name.span(),
                            "top-level read arguments need a provider",
                        ))
                    }
                };
                if self.silk {
                    writeln!(out, "  if true {{\n  DumpPath.beginTable(&mut path)\n  DumpPath.push(&mut path, \"{tag}\")\n  match move FontRef<'a>.{method}(font) {{ Result<{name}<'a>, ReadError>.Success {{ value: table }} => run dump{name}(&mut path, table) Result<{name}<'a>, ReadError>.Failure {{ error }} => run readError(&path, error) }}\n  DumpPath.pop(&mut path)\n  }}").unwrap();
                } else {
                    writeln!(out, "  {{ crate::dump_support::begin_table(); use read_fonts::TableProvider; let path=&format!(\"{{path}}.{tag}\"); match font.{rust_method}() {{ Ok(table) => dump_{name}(out, path, &table)?, Err(error) => writeln!(out, \"{{path}}.error={{}}\", crate::error(error))?, }} }}").unwrap();
                }
                continue;
            }
            if self.silk {
                writeln!(out, "  if true {{\n  DumpPath.beginTable(&mut path)\n  DumpPath.push(&mut path, \"{tag}\")\n  match move FontRef<'a>.tableData(font, Tag.fromU32({tag_value})) {{\n    Option<FontData<'a>>.None => run readError(&path, ReadError.TableIsMissing {{ tag: Tag.fromU32({tag_value}) }})\n    Option<FontData<'a>>.Some {{ value: data }} => {{\n      match move {name}<'a>.read(data) {{ Result<{name}<'a>, ReadError>.Success {{ value: table }} => run dump{name}(&mut path, table) Result<{name}<'a>, ReadError>.Failure {{ error }} => run readError(&path, error) }}\n    }}\n  }}\n  DumpPath.pop(&mut path)\n  }}").unwrap();
            } else {
                writeln!(out,"  {{\n  crate::dump_support::begin_table();\n  let path=&format!(\"{{path}}.{tag}\");\n  let tag=Tag::new(b\"{tag}\");\n  match font.table_data(tag).ok_or(ReadError::TableIsMissing(tag)).and_then({name}::read) {{ Ok(table) => dump_{name}(out, path, &table)?, Err(error) => writeln!(out, \"{{path}}.error={{}}\", crate::error(error))?, }}\n  }}").unwrap();
            }
        }
        self.end(out);
        Ok(())
    }
    fn start(&self, out: &mut String, name: &str, record: bool) {
        self.start_extended(out, name, record);
    }
    fn end(&self, out: &mut String) {
        if !self.silk {
            writeln!(out, "  Ok(())").unwrap();
        }
        writeln!(out, "}}\n").unwrap();
    }
    fn scalar(&self, out: &mut String, typ: &str, value: &str) -> syn::Result<()> {
        if typ == "MajorMinor" {
            for field in ["major", "minor"] {
                if self.silk {
                    writeln!(out,"  DumpPath.push(&mut path, \"{field}\")\n  run scalar(&path, {value}.{field})\n  DumpPath.pop(&mut path)").unwrap();
                } else {
                    writeln!(
                        out,
                        "  writeln!(out, \"{{path}}.{field}={{}}\", {value}.{field})?;"
                    )
                    .unwrap();
                }
            }
            return Ok(());
        }
        let expr = if self.silk {
            match typ {
                "u8" | "i8" | "u16" | "i16" | "u32" | "i32" | "u64" | "i64" => value.into(),
                "LookupFlag" => format!("LookupFlag.toBits({value})"),
                "TupleIndex" | "TupleVariationCount" => format!("{typ}.bits({value})"),
                "Fixed" | "F2Dot14" | "F4Dot12" | "F6Dot10" => format!("{typ}.toBits({value})"),
                "Version16Dot16" => format!("versionBits({value})"),
                "FWord" => format!("FWord.toI16({value})"),
                "UfWord" => format!("UfWord.toU16({value})"),
                "LongDateTime" => format!("LongDateTime.asSecs({value})"),
                "GlyphId16" | "NameId" => format!("{typ}.toU16({value})"),
                "Int24" => format!("Int24.toI32({value})"),
                "Tag" | "Uint24" | "GlyphId24" | "GlyphId" | "Offset16" | "Offset24"
                | "Offset32" => format!("{typ}.toU32({value})"),
                _ => match self.cx.find(typ) {
                    Some(Item::Flags(_)) => format!("{typ}.bits(&{value})"),
                    Some(Item::RawEnum(_)) => format!("{typ}.value({value})"),
                    _ => {
                        return Err(syn::Error::new(
                            proc_macro2::Span::call_site(),
                            format!("unknown dump scalar {typ}"),
                        ))
                    }
                },
            }
        } else {
            match typ {
                "LookupFlag" => format!("{value}.to_bits()"),
                "TupleIndex" | "TupleVariationCount" => format!("{value}.bits()"),
                "Fixed" | "F2Dot14" | "F4Dot12" | "F6Dot10" => format!("{value}.to_bits()"),
                "Version16Dot16" => format!("u32::from_be_bytes({value}.to_be_bytes())"),
                "FWord" => format!("i16::from({value})"),
                "UfWord" => format!("u16::from({value})"),
                "LongDateTime" => format!("{value}.as_secs()"),
                "Tag" => format!("u32::from_be_bytes({value}.to_be_bytes())"),
                "Uint24" | "GlyphId24" | "GlyphId" | "Offset16" | "Offset24" | "Offset32" => {
                    format!("{value}.to_u32()")
                }
                "GlyphId16" | "NameId" => format!("{value}.to_u16()"),
                "Int24" => format!("{value}.to_i32()"),
                _ => match self.cx.find(typ) {
                    Some(Item::Flags(_)) => format!("{value}.bits()"),
                    Some(Item::RawEnum(e)) => format!("{value} as {}", e.typ),
                    _ => value.into(),
                },
            }
        };
        if self.silk {
            writeln!(out, "  run scalar(&path, {expr})").unwrap();
        } else {
            writeln!(out, "  writeln!(out, \"{{path}}={{}}\", {expr})?;").unwrap();
        }
        Ok(())
    }
    fn field_value(&self, out: &mut String, field: &Field) -> syn::Result<()> {
        match &field.typ {
            FieldType::VarLenArray(array) => {
                let typ = array.raw_inner_type();
                if typ != "PString" {
                    return self.variable_array(out, field, &typ.to_string());
                }
                if self.silk {
                    writeln!(out, "  let mut counter = VarLenArray<'a, PString<'a>>.iter(&fieldValue)\n  let mut count: usize = 0\n  while true {{\n    if let Option<Result<PString<'a>, ReadError>>.None = move VarLenIter<'a, PString<'a>>.next(&mut counter) {{ break }}\n    count = count + 1\n  }}\n  DumpPath.push(&mut path, \"length\")\n  run scalar(&path, count)\n  DumpPath.pop(&mut path)\n  let mut iter = VarLenArray<'a, PString<'a>>.iter(&fieldValue)\n  let mut index: usize = 0\n  while index < count {{\n    DumpPath.setIndex(&mut path, index)\n    if let Option<Result<PString<'a>, ReadError>>.Some {{ value: result }} = move VarLenIter<'a, PString<'a>>.next(&mut iter) {{\n      match move result {{ Result<PString<'a>, ReadError>.Success {{ value: item }} => run bytes(&path, PString<'a>.asBytes(&item)) Result<PString<'a>, ReadError>.Failure {{ error }} => run readError(&path, error) }}\n    }}\n    index = index + 1\n  }}\n  DumpPath.clearIndex(&mut path)").unwrap();
                } else {
                    writeln!(out, "  writeln!(out, \"{{path}}.length={{}}\", fieldValue.iter().count())?;\n  for (index, item) in fieldValue.iter().enumerate() {{\n    let path = &format!(\"{{path}}[{{index}}]\");\n    match item {{ Ok(item) => {{ write!(out, \"{{path}}=\")?; for byte in item.as_str().as_bytes() {{ write!(out, \"{{byte:02x}}\")?; }} writeln!(out)?; }}, Err(error) => writeln!(out, \"{{path}}.error={{}}\", crate::error(error))?, }}\n  }}").unwrap();
                }
            }
            FieldType::Scalar { typ } | FieldType::Offset { typ, .. } => {
                let mut value = "fieldValue".to_owned();
                if field.attrs.nullable.is_some() {
                    if self.silk {
                        writeln!(
                            out,
                            "  let rawOffset = Nullable<{typ}>.offset(&fieldValue).*"
                        )
                        .unwrap();
                    } else {
                        writeln!(out, "  let rawOffset = fieldValue.offset();").unwrap();
                    }
                    value = "rawOffset".into();
                }
                self.scalar(out, &typ.to_string(), &value)?;
            }
            FieldType::Struct { typ } => {
                self.dump_args(out, &self.owner_name(field), field, false)?;
                if self.silk {
                    writeln!(out, "  DumpPath.setArguments(&mut path, targetArgs)").unwrap();
                } else {
                    writeln!(out, "  crate::dump_support::set_arguments(target_args);").unwrap();
                }
                if self.silk {
                    writeln!(out, "  run dump{typ}(&mut path, fieldValue, base)").unwrap();
                } else {
                    let borrow = if matches!(
                        self.cx.find(&self.owner_name(field)),
                        Some(Item::Record(_))
                    ) || matches!(self.cx.find(&typ.to_string()), Some(Item::Record(record)) if record.lifetime.is_none())
                    {
                        ""
                    } else {
                        "&"
                    };
                    writeln!(out, "  dump_{typ}(out, path, {borrow}fieldValue, base)?;").unwrap();
                }
            }
            FieldType::ComputedArray(array) => {
                self.computed_array(out, field, &array.raw_inner_type().to_string())?
            }
            FieldType::Array { inner_typ } => {
                let array_type = self.cx.field_type(field)?;
                if self.silk {
                    writeln!(out,"  DumpPath.push(&mut path, \"length\")\n  run scalar(&path, {array_type}.len(&fieldValue))\n  DumpPath.pop(&mut path)\n  let mut index: usize = 0\n  while index < {array_type}.len(&fieldValue) {{\n    DumpPath.setIndex(&mut path, index)").unwrap();
                    match inner_typ.as_ref() {
                        FieldType::Scalar { typ } | FieldType::Offset { typ, .. } => {
                            let scalar_type = if field.attrs.nullable.is_some() {
                                format!("Nullable<{typ}>")
                            } else {
                                typ.to_string()
                            };
                            writeln!(out,"    if let Option<{scalar_type}>.Some {{ value: item }} = move {array_type}.get(&fieldValue, index) {{").unwrap();
                            let item = if field.attrs.nullable.is_some() {
                                format!("Nullable<{typ}>.offset(&item).*")
                            } else {
                                "item".into()
                            };
                            self.scalar(out, &typ.to_string(), &item)?;
                            writeln!(out, "    }}").unwrap();
                        }
                        FieldType::Struct { typ } => {
                            writeln!(out, "    DumpPath.setArguments(&mut path, [0; 3])").unwrap();
                            writeln!(out,"    match move {array_type}.get(&fieldValue, index) {{ Result<{typ}<'a>, ReadError>.Success {{ value: item }} => run dump{typ}(&mut path, item, base) Result<{typ}<'a>, ReadError>.Failure {{ error }} => run readError(&path, error) }}").unwrap();
                        }
                        _ => {
                            return Err(syn::Error::new(
                                field.name.span(),
                                "unsupported dump array",
                            ))
                        }
                    }
                    writeln!(
                        out,
                        "    index = index + 1\n  }}\n  DumpPath.clearIndex(&mut path)"
                    )
                    .unwrap();
                } else {
                    writeln!(out,"  writeln!(out, \"{{path}}.length={{}}\", fieldValue.len())?;\n  for (index, item) in fieldValue.iter().enumerate() {{\n    let path = &format!(\"{{path}}[{{index}}]\");").unwrap();
                    match inner_typ.as_ref() {
                        FieldType::Scalar { typ } | FieldType::Offset { typ, .. } => {
                            writeln!(
                                out,
                                "    let item = {}",
                                if typ == "u8" || typ == "i8" {
                                    "*item;"
                                } else {
                                    "item.get();"
                                }
                            )
                            .unwrap();
                            let item = if field.attrs.nullable.is_some() {
                                "item.offset()"
                            } else {
                                "item"
                            };
                            self.scalar(out, &typ.to_string(), item)?;
                        }
                        FieldType::Struct { typ } => {
                            writeln!(out, "    crate::dump_support::set_arguments([0; 3]); dump_{typ}(out, path, item, base)?;").unwrap();
                        }
                        _ => {
                            return Err(syn::Error::new(
                                field.name.span(),
                                "unsupported dump array",
                            ))
                        }
                    }
                    writeln!(out, "  }}").unwrap();
                }
            }
            _ => return Err(syn::Error::new(field.name.span(), "unsupported dump field")),
        }
        Ok(())
    }
    fn fields(
        &self,
        out: &mut String,
        name: &str,
        fields: &Fields,
        record: bool,
    ) -> syn::Result<()> {
        self.start(out, name, record);
        let owner = self.cx.applied(name);
        if !record {
            if self.silk {
                writeln!(out, "  let base = {owner}.offsetData(&value)").unwrap();
            } else {
                writeln!(out, "  let base = value.offset_data();").unwrap();
            }
        }
        for field in fields.iter() {
            let field_name = camel(&field.name.to_string());
            let typ = self.cx.field_type(field)?;
            if self.silk {
                writeln!(
                    out,
                    "  if true {{\n  DumpPath.push(&mut path, \"{field_name}\")"
                )
                .unwrap();
            } else {
                writeln!(
                    out,
                    "  {{\n  let path = &format!(\"{{path}}.{field_name}\");"
                )
                .unwrap();
            }
            if let FieldType::VarLenArray(array) = &field.typ {
                if array.raw_inner_type() == "TupleVariationHeader" {
                    if self.silk {
                        writeln!(out, "  let range = {owner}.{field_name}ByteRange(&value)\n  let raw = FontData.slice(&base, range.start, range.end) |> Option<FontData<'a>>.unwrapOr(FontData.new(&[]))\n  run bytes(&path, FontData.asBytes(&raw))\n  DumpPath.pop(&mut path)\n  }}").unwrap();
                    } else {
                        writeln!(out, "  let raw = base.slice(value.{}_byte_range()).unwrap_or_default();\n  write!(out, \"{{path}}=\")?; for byte in raw.as_bytes() {{ write!(out, \"{{byte:02x}}\")?; }} writeln!(out)?;\n  }}", field.name).unwrap();
                    }
                    continue;
                }
            }
            let expression = if field.attrs.skip_getter.is_some()
                && !matches!(
                    field.name.to_string().as_str(),
                    "lookup_variation_records" | "shared_tuples_offset"
                ) {
                self.skipped_getter(name, field, &typ)?
            } else if self.silk {
                format!("{owner}.{field_name}(&value)")
            } else {
                format!("value.{}()", field.name)
            };
            if field.is_conditional() {
                if self.silk {
                    writeln!(out,"  match move {expression} {{ Option<{typ}>.Some {{ value: fieldValue }} => {{").unwrap();
                } else {
                    writeln!(out, "  match {expression} {{ Some(fieldValue) => {{").unwrap();
                }
                self.field_value(out, field)?;
                if self.silk {
                    writeln!(out, "  }} Option<{typ}>.None => run absent(&path) }}").unwrap();
                } else {
                    writeln!(out, "  }}, None => writeln!(out, \"{{path}}=none\")?, }}").unwrap();
                }
            } else {
                writeln!(
                    out,
                    "  let fieldValue = {expression}{}",
                    if self.silk { "" } else { ";" }
                )
                .unwrap();
                self.field_value(out, field)?;
            }
            if self.silk {
                writeln!(out, "  DumpPath.pop(&mut path)").unwrap();
            }
            writeln!(out, "  }}").unwrap();
            self.resolved_field(out, name, field, record)?;
        }
        for (prefix, group, function) in [
            ("CoverageFormat", "CoverageTable", "coverage"),
            ("ClassDefFormat", "ClassDef", "classes"),
        ] {
            if let Some(format) = name
                .strip_prefix(prefix)
                .filter(|v| matches!(*v, "1" | "2" | "3" | "4"))
            {
                if self.silk {
                    writeln!(out, "  run extensions_sets.{function}(&mut path, {group}<'a>.Format{format} {{ value: value }})").unwrap();
                } else {
                    writeln!(out, "  crate::extensions_sets::{function}(out, path, &{group}::Format{format}(value.clone()))?;").unwrap();
                }
            }
        }
        if name == "Cmap" || name == "Dmap" {
            let silk_value = if name == "Dmap" {
                "Dmap<'a>.asCmap(&value)"
            } else {
                "value"
            };
            let rust_value = if name == "Dmap" {
                "&value.as_cmap()"
            } else {
                "value"
            };
            if self.silk {
                writeln!(
                    out,
                    "  run extensions_cmap.dumpCmap(&mut path, {silk_value})"
                )
                .unwrap();
            } else {
                writeln!(
                    out,
                    "  crate::extensions_cmap::dump(out, path, {rust_value})?;"
                )
                .unwrap();
            }
        }
        if name == "Post" {
            if self.silk {
                writeln!(out, "  run extensions_post.dumpPost(&mut path, value)").unwrap();
            } else {
                writeln!(out, "  crate::extensions_post::dump(out, path, value)?;").unwrap();
            }
        }
        if matches!(name, "Hmtx" | "HmtxExtended" | "Vmtx" | "VmtxExtended") {
            if self.silk {
                writeln!(out, "  run extensions_metrics.dump{name}(&mut path, value)").unwrap();
            } else {
                writeln!(
                    out,
                    "  crate::extensions_metrics::dump_{}(out, path, value)?;",
                    camel(name)
                )
                .unwrap();
            }
        }
        if name == "ItemVariationStore" {
            if self.silk {
                writeln!(out, "  run dumpStoreEvaluation(&mut path, value)").unwrap();
            } else {
                writeln!(out, "  dump_store_evaluation(out, path, value)?;").unwrap();
            }
        }
        if name == "BitmapSize" {
            if self.silk {
                writeln!(out, "  run dumpBitmapSubtables(&mut path, value, base)").unwrap();
            } else {
                writeln!(out, "  dump_bitmap_subtables(out, path, value, base)?;").unwrap();
            }
        }
        if name == "Strike" {
            if self.silk {
                writeln!(out, "  run dumpStrikeGlyphs(&mut path, value)").unwrap();
            } else {
                writeln!(out, "  dump_strike_glyphs(out, path, value)?;").unwrap();
            }
        }
        if name == "Name" {
            if self.silk {
                writeln!(out, "  run extensions_name.dumpNames(&mut path, value)").unwrap();
            } else {
                writeln!(out, "  crate::extensions_name::dump(out, path, value)?;").unwrap();
            }
        }
        self.end(out);
        if !record {
            self.trait_impl(out, name);
        }
        Ok(())
    }
    fn format(&self, out: &mut String, format: &TableFormat) -> syn::Result<()> {
        let name = format.name.to_string();
        self.start(out, &name, false);
        writeln!(out, "  match value {{").unwrap();
        for v in &format.variants {
            if matches!(self.cx.find(&v.type_name().to_string()), Some(Item::Table(t)) if t.attrs.write_only.is_some())
            {
                continue;
            }
            let variant = &v.name;
            let typ = v.type_name();
            if self.silk {
                writeln!(out,"    {name}<'a>.{variant} {{ value: table }} => {{\n      DumpPath.push(&mut path, \"kind\")\n      run scalar(&path, \"{variant}\")\n      DumpPath.pop(&mut path)\n      run dump{typ}(&mut path, table)\n    }}").unwrap();
            } else {
                writeln!(out,"    {name}::{variant}(table) => {{ writeln!(out, \"{{path}}.kind={variant}\")?; dump_{typ}(out, path, table)?; }}").unwrap();
            }
        }
        writeln!(out, "  }}").unwrap();
        if name == "CmapSubtable" {
            if self.silk {
                writeln!(out, "  run extensions_cmap.dumpSubtable(&mut path, value)").unwrap();
            } else {
                writeln!(
                    out,
                    "  crate::extensions_cmap::subtable(out, path, value)?;"
                )
                .unwrap();
            }
        }
        self.end(out);
        self.trait_impl(out, &name);
        Ok(())
    }
}
