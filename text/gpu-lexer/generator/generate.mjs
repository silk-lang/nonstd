// Generates the Silk modules that embed the two promoted models: their WGSL and their weights.
// Usage: node generator/generate.mjs [--check]   (from text/gpu-lexer)
//
// Inputs are model/tree.json (a promoted tree checkpoint, as gpu-lexer's training writes it),
// model/lite.json and model/lite.wgsl. tree-shader.js, model-layout.js, tree-features.js and
// weights-codec.js are gpu-lexer's own generator modules (MIT, see generator/LICENSE), kept
// unchanged so a newly trained checkpoint produces the shader its training expects.
import { readFileSync, writeFileSync } from "node:fs";
import { createTreeShader } from "./tree-shader.js";
import { runtimeTensorLayout } from "./model-layout.js";
import { unpackWeights } from "./weights-codec.js";

const root = new URL("../", import.meta.url);
const check = process.argv.includes("--check");
const WEIGHT_ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";

const tree = JSON.parse(readFileSync(new URL("model/tree.json", root), "utf8"));
const lite = JSON.parse(readFileSync(new URL("model/lite.json", root), "utf8"));
const liteShader = readFileSync(new URL("model/lite.wgsl", root), "utf8");

// Silk byte-string literal: printable ASCII stays as is, everything else is escaped.
function bytes(value) {
  let text = 'b"';
  for (const byte of value) {
    if (byte === 34 || byte === 92) text += "\\" + String.fromCharCode(byte);
    else if (byte === 10) text += "\\n";
    else if (byte >= 32 && byte < 127) text += String.fromCharCode(byte);
    else text += "\\x" + byte.toString(16).padStart(2, "0");
  }
  return text + '"';
}

function ascii(value) {
  return bytes(Buffer.from(value, "latin1"));
}

// Row-major [rows][columns] symbols to column-major, as the shader reads them.
function transposeSymbols(values, rows, columns) {
  let result = "";
  for (let column = 0; column < columns; column++) {
    for (let row = 0; row < rows; row++) result += values[row * columns + column];
  }
  return result;
}

// The compact runtime tensor order: unreachable feature rows dropped, matrices transposed.
function treeWeights(model) {
  let offset = 0;
  const ends = [];
  const scales = [];
  let weights = "";
  for (const tensor of runtimeTensorLayout(model)) {
    if (tensor.offset !== offset) throw new Error(`runtime tensor ${tensor.name} is not contiguous`);
    offset += tensor.length;
    ends.push(offset);
    scales.push(tensor.scale);
    let values = "";
    for (let range = 0; range < tensor.sourceRanges.length; range += 2) {
      values += model.weights.slice(tensor.sourceRanges[range], tensor.sourceRanges[range + 1]);
    }
    weights += tensor.transpose ? transposeSymbols(values, ...tensor.transpose) : values;
  }
  if (weights.length !== offset || [...weights].some((symbol) => !WEIGHT_ALPHABET.includes(symbol))) {
    throw new Error("runtime tree weights are invalid");
  }
  return { ends, scales, weights };
}

function float(value) {
  const text = String(value);
  return /[.e]/.test(text) ? text : text + ".0";
}

function littleEndian(array) {
  return new Uint8Array(array.buffer, array.byteOffset, array.byteLength);
}

const header = "// Generated by text/gpu-lexer/generator/generate.mjs from text/gpu-lexer/model; do not edit.\n";
const { ends, scales, weights } = treeWeights(tree);
const { planes, fp } = unpackWeights(lite.sym, lite.f16, lite.meta);
const steps = lite.pipeline;
const models = header +
  "//! The promoted tree and lite models: shapes, weights and dispatch steps.\n\n" +
  `/// Hidden channels of the tree model; every part keeps this many states.\n` +
  `pub const TREE_HIDDEN: usize = ${tree.hiddenSize}\n` +
  `/// Runtime tensors in buffer order; tensor \`i\` ends at \`TREE_TENSOR_ENDS[i]\` and has scale \`TREE_TENSOR_SCALES[i]\`.\n` +
  `pub const TREE_TENSOR_ENDS: [usize; ${ends.length}] = [${ends.join(", ")}]\n` +
  `pub const TREE_TENSOR_SCALES: [f64; ${scales.length}] = [${scales.map(float).join(", ")}]\n` +
  `/// One int6 code per weight, in the alphabet \`A-Z a-z 0-9 - _\` (0 to 63).\n` +
  `pub fn treeWeights() -> &'static [u8] { return ${ascii(weights)} }\n\n` +
  `/// Hidden channels of the lite model.\n` +
  `pub const LITE_DIM: usize = ${lite.meta.config.dim}\n` +
  `/// Dispatch steps in order: entry point and the token tile one workgroup covers (0: one per job).\n` +
  `pub const LITE_STEP_COUNT: usize = ${steps.length}\n` +
  `pub fn liteStep(index: usize) -> &'static [u8] {\n  return match index {\n${steps.map((step, index) => `    ${index} => ${ascii(step.entry)}\n`).join("")}    _ => b""\n  }\n}\n` +
  `pub const LITE_TILES: [u32; ${steps.length}] = [${steps.map((step) => step.tile).join(", ")}]\n` +
  `/// Bit-packed weight planes, little-endian u32 words.\n` +
  `pub fn litePlanes() -> &'static [u8] { return ${bytes(littleEndian(planes))} }\n` +
  `/// Scales, biases and gains, little-endian f32.\n` +
  `pub fn liteFloats() -> &'static [u8] { return ${bytes(littleEndian(fp))} }\n`;

const shaders = header +
  "//! WGSL for both models. The tree shader has an f16 variant for devices with shader-f16.\n\n" +
  `pub fn tree() -> &'static [u8] { return ${bytes(Buffer.from(createTreeShader(tree, { f16: false })))} }\n` +
  `pub fn treeF16() -> &'static [u8] { return ${bytes(Buffer.from(createTreeShader(tree, { f16: true })))} }\n` +
  `pub fn lite() -> &'static [u8] { return ${bytes(Buffer.from(liteShader))} }\n`;

const outputs = [["src/generated_models.silk", models], ["src/generated_shaders.silk", shaders]];
const stale = [];
for (const [path, text] of outputs) {
  const url = new URL(path, root);
  if (check) {
    let current = "";
    try { current = readFileSync(url, "utf8"); } catch {}
    if (current !== text) stale.push(path);
  } else {
    writeFileSync(url, text);
  }
}
if (stale.length) {
  console.error(`stale generated modules: ${stale.join(", ")}; run node text/gpu-lexer/generator/generate.mjs`);
  process.exit(1);
}
